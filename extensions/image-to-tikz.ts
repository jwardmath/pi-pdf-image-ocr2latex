const imageToTikzTool = defineTool({
  name: "image_to_tikz",
  label: "Image to TikZ",
  description:
    "Convert an image file or PDF (up to 300 pages) into compilable LaTeX TikZ source " +
    "using a vision model (default qwen2.5vl:7b via Ollama). Accepts a path to an image (png/jpg/webp/gif/bmp/tif), " +
    "a PDF, or a directory. Writes <basename>.tikz.tex next to each input. Use for diagrams, sketches, " +
    "figures, and charts that need accurate TikZ reproduction.",
  parameters: Type.Object({
    path: Type.String({ description: "Path to an image, PDF, or directory of images/PDFs to convert." }),
    model: Type.Optional(Type.String({ description: `Vision model id. Default: ${DEFAULT_MODEL}` })),
    provider: Type.Optional(Type.String({ description: `Model provider id. Default: ${DEFAULT_PROVIDER}` })),
    scale: Type.Optional(Type.Number({ description: "Rasterization scale for PDF pages. Default 2." })),
    dpi: Type.Optional(Type.Number({ description: "PDF rasterization DPI. Default 150." })),
    pages: Type.Optional(Type.String({ description: "Page range to convert, e.g. '1-5,7'. Images ignore this." })),
    out: Type.Optional(Type.String({ description: "Output directory. Default: next to input." })),
    keepImages: Type.Optional(Type.Boolean({ description: "Keep rasterized page images on disk. Default false." })),
    multiple: Type.Optional(Type.Boolean({ description: "Emit one .tex per PDF page (foo_p1.tikz.tex). Default false." })),
  }),

  async execute(_toolCallId, params, signal, _onUpdate, toolCtx) {
    const raw = params as Record<string, unknown>;
    const opts = normalizeOptions(raw, DEFAULT_MODEL, DEFAULT_PROVIDER);
    const inputs = [String(params.path)];
    const out = await runConversion(toolCtx, inputs, opts);
    return {
      content: [{ type: "text", text: out.summary }],
      details: { summary: out.summary },
    };
  },
});

// ---------------------------------------------------------------------------
// Command + extension registration
// ---------------------------------------------------------------------------

function parseCommandArgs(rawArgs: string): { inputs: string[]; opts: Record<string, unknown> } {
  const tokens = rawArgs.trim().split(/\s+/).filter(Boolean);
  const inputs: string[] = [];
  const opts: Record<string, unknown> = { multiple: undefined };
  const BOOLEAN_FLAGS = new Set(["keep-images", "swap-model", "swap"]);
  let i = 0;
  while (i < tokens.length) {
    const t = tokens[i];
    if (t.startsWith("--")) {
      const key = t.slice(2);
      const next = tokens[i + 1];
      if (BOOLEAN_FLAGS.has(key)) {
        opts[key] = true;
        i += 1;
      } else if (next && !next.startsWith("--")) {
        opts[key] = next;
        i += 2;
      } else {
        opts[key] = true;
        i += 1;
      }
    } else {
      inputs.push(t);
      i += 1;
    }
  }
  for (const k of ["keep-images"]) {
    if (opts[k] === undefined) delete opts[k];
  }
  return { inputs, opts };
}

export default function (pi: ExtensionAPI) {
  pi.registerTool(imageToTikzTool);

  pi.registerCommand("img2tikz", {
    description: "Convert an image or PDF to LaTeX TikZ using a pluggable vision model (default qwen2.5vl:7b via Ollama)",
    handler: async (args, ctx) => {
      const { inputs, opts } = parseCommandArgs(args || "");
      if (inputs.length === 0) {
        ctx.ui.notify?.("Usage: /img2tikz <image-or-pdf> [...] [--model qwen2.5vl:7b] [--provider ollama] [--dpi 150] [--scale 2] [--pages 1-5] [--out dir] [--multiple] [--keep-images] [--swap-model]", "error");
        return;
      }

      // Resolve model + provider (allow flags and env overrides).
      const modelId = typeof opts.model === "string" && opts.model.trim() ? opts.model.trim() : DEFAULT_MODEL;
      const providerId = typeof opts.provider === "string" && opts.provider.trim() ? opts.provider.trim() : DEFAULT_PROVIDER;
      const resolvedOpts = normalizeOptions(opts, modelId, providerId);

      // Validate model exists early for a clear error.
      const found = ctx.modelRegistry.find(resolvedOpts.provider, resolvedOpts.model);
      if (!found) {
        const avail = ctx.modelRegistry.getAll().map((m) => `${m.provider}:${m.id}`);
        ctx.ui.notify?.(`Model "${resolvedOpts.model}" on provider "${resolvedOpts.provider}" not found. Available: ${avail.join(", ") || "(none)"}`, "error");
        return;
      }

      // Expand directories and validate before starting.
      let files: string[] = [];
      try {
        for (const input of inputs) {
          const list = listInputFiles(input);
          files.push(...list);
        }
      } catch (e: any) {
        ctx.ui.notify?.(e?.message || String(e), "error");
        return;
      }

      if (files.length === 0) {
        ctx.ui.notify?.("No supported image/PDF files found.", "error");
        return;
      }

      // --- Optional session-model swap (opt-in via --swap-model). The vision
      //     call already routes to the requested provider/model directly, so
      //     swapping the active session model is only needed when the user
      //     explicitly wants it (e.g. to have the follow-up turn use the
      //     vision model). ---
      const wantSwap = opts["swap-model"] === true || opts.swap === true;
      const previousModel = ctx.model;
      const visionModel = ctx.modelRegistry.find(resolvedOpts.provider, resolvedOpts.model);
      let switched = false;
      if (wantSwap && visionModel && previousModel?.id !== visionModel.id) {
        const ok = await pi.setModel(visionModel);
        if (ok) switched = true;
        else ctx.ui.notify?.(`Could not switch session model to "${resolvedOpts.model}"; using it only for the vision call.`, "warning");
      }

      try {
        const { summary, texPaths } = await runConversion(
          ctx,
          files,
          { ...resolvedOpts, multiple: resolvedOpts.multiple },
        );
        ctx.ui.notify?.(summary, "info");

        // --- Compile each generated .tex to a .pdf using pdflatex (no AI model). ---
        for (const texPath of texPaths) {
          ctx.ui.notify?.(`Compiling ${basename(texPath)} with pdflatex…`, "info");
          const { pdfPath, error } = compileTexFile(texPath);
          if (pdfPath) {
            ctx.ui.notify?.(`✓ PDF produced: ${relative(process.cwd(), pdfPath)}`, "info");
          } else {
            ctx.ui.notify?.(`✗ Compile failed for ${basename(texPath)}:\n${error}`, "error");
          }
        }
      } catch (e: any) {
        ctx.ui.notify?.(e?.message || String(e), "error");
      } finally {
        // --- Restore the model that was active before /img2tikz was called. ---
        if (switched && previousModel) {
          try {
            await pi.setModel(previousModel);
            ctx.ui.notify?.(`Restored model to ${previousModel.id}.`, "info");
          } catch (e: any) {
            ctx.ui.notify?.(`Could not restore previous model: ${e?.message || String(e)}`, "warning");
          }
        }
      }
    },
  });
}
